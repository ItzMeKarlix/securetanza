/**
 * Turns public/tanza_cavite.geojson (463 KB) into the light SVG path module the
 * sign-in pages draw from, so they show the real barangay boundaries without
 * downloading the whole GeoJSON before anyone has signed in.
 *
 *   bun scripts/build-tanza-outline.ts
 *
 * Re-run it whenever the GeoJSON changes.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { POLICE_STATION_COORD } from "../constants/map-constants";

type Ring = number[][];
interface Feature {
  properties: { adm4_en?: string };
  geometry: { type: "Polygon"; coordinates: Ring[] } | { type: "MultiPolygon"; coordinates: Ring[][] };
}

const WIDTH = 1000;
/** Simplification tolerance in viewBox units: well under a pixel at panel size. */
const TOLERANCE = 0.9;

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const geo = JSON.parse(readFileSync(join(root, "public/tanza_cavite.geojson"), "utf8")) as { features: Feature[] };

const outerRings = (feature: Feature): Ring[] =>
  feature.geometry.type === "Polygon"
    ? [feature.geometry.coordinates[0]]
    : feature.geometry.coordinates.map((polygon) => polygon[0]);

let minLon = Infinity, maxLon = -Infinity, minLat = Infinity, maxLat = -Infinity;
for (const feature of geo.features) {
  for (const ring of outerRings(feature)) {
    for (const [lon, lat] of ring) {
      minLon = Math.min(minLon, lon); maxLon = Math.max(maxLon, lon);
      minLat = Math.min(minLat, lat); maxLat = Math.max(maxLat, lat);
    }
  }
}

// Equirectangular, corrected for latitude so the shape isn't stretched east–west.
const kx = Math.cos((((minLat + maxLat) / 2) * Math.PI) / 180);
const scale = WIDTH / ((maxLon - minLon) * kx);
const height = Math.round((maxLat - minLat) * scale);
const project = ([lon, lat]: number[]) => [(lon - minLon) * kx * scale, (maxLat - lat) * scale];

function simplify(points: number[][]): number[][] {
  if (points.length < 3) return points;
  const [ax, ay] = points[0];
  const [bx, by] = points[points.length - 1];
  const length = Math.hypot(bx - ax, by - ay) || 1;
  let worst = 0, index = 0;
  for (let i = 1; i < points.length - 1; i++) {
    const [px, py] = points[i];
    const distance = Math.abs((bx - ax) * (ay - py) - (ax - px) * (by - ay)) / length;
    if (distance > worst) { worst = distance; index = i; }
  }
  if (worst <= TOLERANCE) return [points[0], points[points.length - 1]];
  return [...simplify(points.slice(0, index + 1)).slice(0, -1), ...simplify(points.slice(index))];
}

const round = (n: number) => Math.round(n * 10) / 10;
const barangays = geo.features
  .map((feature) => ({
    name: feature.properties.adm4_en ?? "",
    d: outerRings(feature)
      .map((ring) => {
        // Split the closed ring in two so simplification keeps its far side.
        const projected = ring.map(project);
        const half = Math.floor(projected.length / 2);
        const kept = [...simplify(projected.slice(0, half + 1)).slice(0, -1), ...simplify(projected.slice(half))];
        return `M${kept.map(([x, y]) => `${round(x)} ${round(y)}`).join("L")}Z`;
      })
      .join(""),
  }))
  .sort((a, b) => a.name.localeCompare(b.name));

const station = project([POLICE_STATION_COORD[1], POLICE_STATION_COORD[0]]);

const out = `// Generated by scripts/build-tanza-outline.ts from public/tanza_cavite.geojson. Do not edit.

export const TANZA_VIEWBOX = "0 0 ${WIDTH} ${height}";

/** ViewBox units per kilometre, for the scale bar (1° of latitude ≈ 110.6 km). */
export const TANZA_UNITS_PER_KM = ${round(scale / 110.6)};

/** Tanza Municipal Police Station (constants/map-constants.ts), in viewBox units. */
export const TANZA_STATION = { x: ${round(station[0])}, y: ${round(station[1])} };

export const TANZA_BARANGAYS: ReadonlyArray<{ name: string; d: string }> = ${JSON.stringify(barangays, null, 0).replace(/\},\{/g, "},\n  {").replace(/^\[/, "[\n  ").replace(/\]$/, ",\n]")};
`;

writeFileSync(join(root, "components/auth/tanza-outline-paths.ts"), out);
console.log(`${barangays.length} barangays, ${(out.length / 1024).toFixed(1)} KB, viewBox 0 0 ${WIDTH} ${height}`);
